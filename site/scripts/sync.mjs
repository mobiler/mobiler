// Generates the site pages that already exist elsewhere in the repo, so there is one source of truth:
// - the Saldo tutorial (docs/tutorial/saldo) -> src/content/docs/tutorial/
// - built-in capabilities (capabilities.json) -> src/content/docs/reference/capabilities.md
// - bundled plugins (mobiler/plugins/*/mobiler-plugin.toml) -> src/content/docs/reference/plugins.md
// - demo screenshots (demos/*/screenshots) -> public/demos/
// Everything written here is gitignored. Runs before `astro dev` and `astro build`.

import { cpSync, existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = resolve(SITE, '..');
const DOCS = join(SITE, 'src/content/docs');
export const GITHUB = 'https://github.com/mobiler/mobiler';

/** A repo-relative path as a GitHub link: `tree` for a folder, `blob` for a file. */
function githubUrl(repoPath, hash = '') {
	const full = join(REPO, repoPath);
	if (!existsSync(full)) throw new Error(`link to a path that doesn't exist: ${repoPath}`);
	const kind = statSync(full).isDirectory() ? 'tree' : 'blob';
	return `${GITHUB}/${kind}/main/${repoPath}${hash}`;
}

/** Split the first `# Heading` off a Markdown file: Starlight renders the title from frontmatter. */
function takeTitle(md) {
	const m = md.match(/^# (.+)\n+/m);
	if (!m) throw new Error('no # title');
	const title = m[1].replace(/\*\*/g, '').replace(/`/g, '').trim();
	return { title, body: md.slice(0, m.index) + md.slice(m.index + m[0].length) };
}

function frontmatter(fields) {
	const lines = Object.entries(fields).map(([k, v]) =>
		typeof v === 'object' ? `${k}:\n${Object.entries(v).map(([a, b]) => `  ${a}: ${JSON.stringify(b)}`).join('\n')}` : `${k}: ${JSON.stringify(v)}`,
	);
	return `---\n${lines.join('\n')}\n---\n\n`;
}

const GENERATED = '<!-- Generated by site/scripts/sync.mjs from the repository. Edit the source, not this page. -->\n\n';

/** Repo-relative Markdown links -> site routes (chapters) or GitHub (anything else); images -> raw files. */
function rewriteLinks(md, f, files, slugOf) {
	return md.replace(/(!?)\]\(([^)\s]+)\)/g, (whole, bang, target) => {
		if (/^[a-z]+:/i.test(target) || target.startsWith('#')) return whole;
		const [path, hash = ''] = target.split(/(?=#)/);
		if (!bang && files.includes(path)) return `](/tutorial/${slugOf(path)}${slugOf(path) ? '/' : ''}${hash})`;
		const repoPath = posix.normalize(posix.join('docs/tutorial/saldo', path)).replace(/\/$/, '');
		if (repoPath.startsWith('..')) throw new Error(`${f}: link leaves the repo: ${target}`);
		if (bang) {
			if (!existsSync(join(REPO, repoPath))) throw new Error(`${f}: image doesn't exist: ${target}`);
			return `${bang}](https://raw.githubusercontent.com/mobiler/mobiler/main/${repoPath})`;
		}
		return `](${githubUrl(repoPath, hash)})`;
	});
}

function syncTutorial() {
	const src = join(REPO, 'docs/tutorial/saldo');
	const out = join(DOCS, 'tutorial');
	rmSync(out, { recursive: true, force: true });
	mkdirSync(out, { recursive: true });
	const files = readdirSync(src).filter((f) => f.endsWith('.md')).sort();
	const slugOf = (f) => (f === 'README.md' ? '' : f.replace(/\.md$/, ''));
	for (const f of files) {
		const { title, body } = takeTitle(readFileSync(join(src, f), 'utf8'));
		// Rewrite links outside fenced code only: a chapter's code may contain `](` legitimately.
		const rewritten = body
			.split(/(^```[\s\S]*?^```)/m)
			.map((part, i) => (i % 2 ? part : rewriteLinks(part, f, files, slugOf)))
			.join('');
		const order = f === 'README.md' ? 0 : Number.parseInt(f, 10);
		const name = f === 'README.md' ? 'index.md' : f;
		const label = f === "README.md" ? "Overview" : `${order}. ${title.replace(/^Chapter \d+ — /, "")}`;
		const editUrl = `${GITHUB}/edit/main/docs/tutorial/saldo/${f}`;
		writeFileSync(join(out, name), frontmatter({ title, editUrl, sidebar: { order, label } }) + GENERATED + rewritten);
	}
	return files.length;
}

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function syncCapabilities() {
	const { capabilities } = JSON.parse(readFileSync(join(REPO, 'capabilities.json'), 'utf8'));
	const shown = capabilities.filter((c) => c.tier === 'free' && c.status !== 'planned');
	const rows = shown.map((c) => `| ${cell(c.name)} | \`${cell(c.api)}\` | ${cell(c.since)} | ${cell(c.notes)} |`);
	const planned = capabilities.filter((c) => c.status === 'planned' && c.tier === 'free');
	const md =
		frontmatter({ title: 'Built-in capabilities', description: 'Device and platform features every Mobiler app can call from Rust, with no plugin to add.', editUrl: `${GITHUB}/edit/main/capabilities.json` }) +
		GENERATED +
		`Built-in capabilities ship in every app made by \`mobiler new\`. Your core calls them through \`cx\`; each shell (Android, iOS, web) fulfils the call natively and sends the answer back as one of your messages.\n\n` +
		`| Capability | API | Since | Notes |\n|---|---|---|---|\n${rows.join('\n')}\n` +
		(planned.length ? `\n**Planned:** ${planned.map((c) => c.name).join(', ')}.\n` : '') +
		`\nMore device features come as [plugins](/reference/plugins/).\n`;
	writeFileSync(join(DOCS, 'reference/capabilities.md'), md);
	return shown.length;
}

/** The two keys we need from a plugin manifest, without a TOML dependency: `name` and `summary` are top-level strings. */
function manifestField(text, key) {
	const top = text.split(/^\[/m)[0];
	const m = top.match(new RegExp(`^${key}\\s*=\\s*"((?:[^"\\\\]|\\\\.)*)"`, 'm'));
	return m ? m[1].replace(/\\"/g, '"') : undefined;
}

/** Manifest summaries carry internal tier tags ("(free)", "— free, bundled (EXPERIMENTAL)"); keep the facts. */
export function publicSummary(s) {
	return s
		.replace(/\s*—\s*free, bundled \(EXPERIMENTAL\)/, ' (experimental)')
		.replace(/\s*\(free\)/, '')
		.replace(/\(free sample\)/, '(sample)')
		.replace(/\(free[;,] /, '(')
		.replace(/EXPERIMENTAL/g, 'experimental')
		.trim();
}

function syncPlugins() {
	const dir = join(REPO, 'mobiler/plugins');
	const plugins = readdirSync(dir)
		.filter((d) => existsSync(join(dir, d, 'mobiler-plugin.toml')))
		.sort()
		.map((d) => {
			const text = readFileSync(join(dir, d, 'mobiler-plugin.toml'), 'utf8');
			const name = manifestField(text, 'name');
			const summary = manifestField(text, 'summary');
			if (!name || !summary) throw new Error(`mobiler/plugins/${d}: manifest needs name and summary`);
			return { name, summary, path: `mobiler/plugins/${d}` };
		});
	const rows = plugins.map((p) => `| [\`${p.name}\`](${githubUrl(p.path)}) | ${cell(publicSummary(p.summary))} |`);
	const md =
		frontmatter({ title: 'Plugins', description: 'Bundled plugins: native features you add to an app with one command.', editUrl: `${GITHUB}/tree/main/mobiler/plugins` }) +
		GENERATED +
		`Plugins ship inside the \`mobiler\` CLI. Adding one copies its Android and iOS code into your app's shells and registers it, so your Rust core can call it:\n\n` +
		'```sh\nmobiler plugin add sqlite\nmobiler plugin add biometric\n```\n\n' +
		`The plugin's native half is part of your app from then on. When a new CLI release updates a plugin, \`mobiler upgrade\` tells you, and running \`mobiler plugin add <name>\` again brings the new version in.\n\n` +
		`| Plugin | What it does |\n|---|---|\n${rows.join('\n')}\n`;
	writeFileSync(join(DOCS, 'reference/plugins.md'), md);
	return plugins.length;
}

function syncScreenshots() {
	const out = join(SITE, 'public/demos');
	rmSync(out, { recursive: true, force: true });
	let n = 0;
	for (const demo of readdirSync(join(REPO, 'demos'))) {
		const shots = join(REPO, 'demos', demo, 'screenshots');
		if (!existsSync(shots)) continue;
		// Never follow a symlink: only real image files may reach the published site.
		cpSync(shots, join(out, demo), { recursive: true, filter: (src) => !lstatSync(src).isSymbolicLink() });
		n += readdirSync(shots).length;
	}
	return n;
}

/** Hand-written pages quote crate versions (`mobiler-core = "0.48"`); fail the build when one is behind the repo. */
function checkVersions() {
	// The template's pins are what `mobiler new` writes today, so they are published versions.
	const tmpl = (f, re) => readFileSync(join(REPO, f), 'utf8').match(re)[1];
	const want = {
		'mobiler-core': tmpl('mobiler/templates/shared/Cargo.toml.tmpl', /^mobiler-core = "([^"]+)"/m),
		crux_core: tmpl('mobiler/templates/Cargo.toml.tmpl', /^crux_core = "([^"]+)"/m),
		// The template has no web client; the CLI's upgrade target is the published mobiler-web (ADR-0066).
		'mobiler-web': tmpl('mobiler/src/upgrade.rs', /^const MOBILER_WEB_PIN: &str = "([^"]+)";/m),
	};
	const stale = [];
	const walk = (dir) => {
		for (const e of readdirSync(dir, { withFileTypes: true })) {
			const p = join(dir, e.name);
			if (e.isDirectory()) walk(p);
			else if (/\.mdx?$/.test(e.name)) {
				for (const m of readFileSync(p, 'utf8').matchAll(/\b(mobiler-core|mobiler-web|crux_core) = (?:\{[^}\n]*?\bversion = )?"([^"]+)"/g)) {
					if (m[2] !== want[m[1]]) stale.push(`${relative(SITE, p)}: ${m[1]} = "${m[2]}", the repo is at "${want[m[1]]}"`);
				}
			}
		}
	};
	walk(DOCS);
	if (stale.length) throw new Error(`stale versions on the site:\n${stale.join('\n')}`);
}

mkdirSync(join(DOCS, 'reference'), { recursive: true });
const counts = { tutorial: syncTutorial(), capabilities: syncCapabilities(), plugins: syncPlugins(), screenshots: syncScreenshots() };
checkVersions();
console.log(`sync: ${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ')} (from ${relative(process.cwd(), REPO) || '.'})`);
